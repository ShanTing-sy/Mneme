<template>
  <div class="mneme-tab-body">
    <div class="mneme-section-title">使用说明</div>

    <h3 class="mneme-help-title">Mneme 是什么</h3>
    <p class="mneme-entry-body">
      一个卷宗式记忆插件。每轮对话结束后，模型会在回复末尾附带一小段结构化记忆，插件把它收进账本；记忆块只从发给模型的内容里剔除，聊天记录本身保留；下一次生成前，再把相关记忆注入提示词。
    </p>

    <h3 class="mneme-help-title">五个标签页</h3>
    <p class="mneme-entry-body">
      <b>记忆</b>：每条 AI 回复一条摘要；满 10 条自动封卷成册。<br />
      <b>羁绊</b>：好感度、角色对 user 的印象、重要事件。<br />
      <b>提示词</b>：把提示词与设置存成多份命名配置，点击切换；设置快照需手动「应用设置」。<br />
      <b>道具</b>：获得的物品、来源与作用。<br />
      <b>剧情线</b>：解析角色卡与世界书得到的一条折叠时间轴，默认只给模型「当前节点」。
    </p>

    <h3 class="mneme-help-title">副 API</h3>
    <p class="mneme-entry-body">
      右上角 <b>⇄</b> 按钮。默认由主模型在正文末尾写 MNEME 块；切到「副 API」后，
      每轮回复会单独请求一条总结，主模型不再写记录块。<br /><br />
      副 API 支持两种来源：酒馆「连接配置管理」里已保存的配置，或自定义 OpenAI 兼容端点
      （基础 URL + 密钥 + 模型）。每条副 API 可单独绑定提示词，并设置温度、top_p、
      最大输出、超时与重试次数。初始羁绊 / 剧情线解析也跟随这里的来源。
    </p>

    <h3 class="mneme-help-title">世界书注入</h3>
    <p class="mneme-entry-body">
      设置 → 记忆注入，可把「扩展提示词」换成「世界书」。插件会按
      <b>当前聊天 + 角色</b> 自动创建一本 `Mneme·角色·聊天` 世界书，并绑定为聊天世界书。<br /><br />
      条目结构：记录要求、长期记忆、短期记忆（常驻），重要记忆、永久记忆、永久物品、
      角色印象（关键词触发）。短期记忆满卷后自动总结成复盘并追加到长期记忆。<br /><br />
      当前聊天已有其他世界书时不会自动替换；可在设置里点「替换绑定」。世界书写入失败时
      会自动退回扩展提示词，避免记忆断档。
    </p>

    <h3 class="mneme-help-title">常见问题</h3>
    <p class="mneme-entry-body">
      <b>模型没有输出记忆怎么办？</b><br />
      面板会给出提示。可在「记忆」标签手动补录；正文不会受任何影响。<br /><br />
      <b>为什么聊天里还能看到记忆块？</b><br />
      记忆块只在对模型生成时剔除，不会删除或改写聊天记录。设置里的
      「发送给模型的最新轮数」也只减少发给模型的原始对话，不会隐藏聊天楼层。<br /><br />
      <b>剧情线什么时候生成？</b><br />
      默认关闭。可在设置里开启「新聊天自动生成」，或在「剧情线」标签手动点「重新解析时间轴」。<br /><br />
      <b>记忆存在哪里？</b><br />
      存在当前聊天的元数据里，导出聊天时一并带走；换聊天互不影响。<br /><br />
      <b>会不会剧透？</b><br />
      时间轴在面板里默认折叠；注入给模型的默认只有「当前节点」，并附带禁止说破的约束。<br /><br />
      <b>删了消息会怎样？</b><br />
      插件按正文指纹重新对齐：还存在的消息保留记忆，被删掉的条目连同其羁绊事件一起移除。
    </p>
